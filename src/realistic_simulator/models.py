from dataclasses import dataclass, field
from typing import Optional, List, Dict, Tuple

# ─────────────────────────────────────────────────────────────────────────────
# End-Term / Pipeline State Models (Backward Compatible)
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class APState:
    """Represents the configuration and state of an Access Point."""
    ap_id: str
    channel: int
    channel_width: int  # in MHz (e.g., 20, 40, 80)
    base_noise: float = -95.0
    x: float = 0.0
    y: float = 0.0
    freq_mhz: float = 5180.0
    tx_power_dbm: float = 20.0
    channel_capacity_mbps: float = 300.0
    
    # Iteration 1 Extensions
    spatial_streams: int = 2
    guard_interval_us: float = 0.8
    antenna_gain_dbi: float = 3.0
    noise_figure_db: float = 5.0
    bss_color: int = 1


@dataclass
class ClientState:
    """Represents a connected client."""
    client_id: str
    demand_mbps: float
    x: float = 0.0
    y: float = 0.0
    wall_count: int = 0
    
    # Iteration 1 Extensions
    velocity_mps: float = 0.0
    direction_rad: float = 0.0
    device_type: str = "laptop"
    application_type: str = "browsing"
    antenna_gain_dbi: float = 0.0
    noise_figure_db: float = 7.0
    mobility_model: str = "stationary"


@dataclass
class QoE:
    """Quality of Experience category and score."""
    score: float
    category: str


@dataclass
class InterferenceEvent:
    """Models an external interference event (e.g., Microwave, BLE)."""
    event_type: str
    noise_boost_db: float
    airtime_boost_percent: float
    duration_minutes: int
    active: bool = False


