@dataclass
class TelemetryRecord:
    """The final telemetry output generated by the simulator."""
    ap_id: str
    channel: int
    client_count: int
    rssi: float
    noise_floor: float
    snr: float
    airtime_utilization: float
    retry_rate: float
    qoe_score: float
    qoe_category: str
    interference_type: str = "None"
    distance: float = 0.0
    freq_mhz: float = 5180.0
    tx_power: float = 20.0
    wall_count: int = 0
    wall_loss: float = 0.0
    recommendations: list = None
    
    # Iteration 1 Extensions (Nullable for backward compatibility)
    sinr: Optional[float] = None
    mcs_index: Optional[int] = None
    phy_rate_mbps: Optional[float] = None
    per: Optional[float] = None
    latency_ms: Optional[float] = None
    throughput_mbps: Optional[float] = None
    
    # Iteration 4 Extension: Sensing Radio
    sensing_report: Optional[dict] = None

    def to_dict(self) -> dict:
        d = {
            "ap_id": self.ap_id,
            "channel": self.channel,
            "client_count": self.client_count,
            "rssi": round(self.rssi, 2),
            "noise_floor": round(self.noise_floor, 2),
            "snr": round(self.snr, 2),
            "airtime_utilization": round(self.airtime_utilization, 2),
            "retry_rate": round(self.retry_rate, 4),
            "qoe_score": round(self.qoe_score, 1),
            "qoe_category": self.qoe_category,
            "interference_type": self.interference_type,
            "distance": round(self.distance, 2),
            "freq_mhz": round(self.freq_mhz, 1),
            "tx_power": round(self.tx_power, 1),
            "wall_count": self.wall_count,
            "wall_loss": round(self.wall_loss, 2),
            "recommendations": self.recommendations or []
        }
        
        # Add new fields if they exist
        if self.sinr is not None:
            d["sinr"] = round(self.sinr, 2)
        if self.mcs_index is not None:
            d["mcs_index"] = self.mcs_index
        if self.phy_rate_mbps is not None:
            d["phy_rate_mbps"] = round(self.phy_rate_mbps, 2)
        if self.per is not None:
            d["per"] = round(self.per, 4)
        if self.latency_ms is not None:
            d["latency_ms"] = round(self.latency_ms, 2)
        if self.throughput_mbps is not None:
            d["throughput_mbps"] = round(self.throughput_mbps, 2)
            
        return d
