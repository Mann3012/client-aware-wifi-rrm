# Telemetry Output
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class TelemetryRecord:
    """
    The final telemetry output generated by the simulator.

    Field classification:
      Network-wide (averaged across all clients):
        rssi, snr, noise_floor, retry_rate, airtime_utilization,
        qoe_score, qoe_category, wall_loss, wall_count, distance

      Per-link, representative client (client nearest to avg distance):
        path_loss_db, estimated_rx_power_dbm, sinr_db,
        mcs_index, phy_rate_mbps, latency_ms, throughput_mbps

      AP configuration (constant per step):
        tx_power, freq_mhz, channel

    The representative client is chosen as the client whose Euclidean
    distance from the AP is closest to the mean of all client distances.
    This ensures all per-link metrics are internally consistent (they all
    derive from the same real client link, not a hypothetical arithmetic
    average of log-scale dB values).
    """
    ap_id: str
    channel: int
    client_count: int
    rssi: float                    # Network avg received power (dBm)
    noise_floor: float             # Network avg noise floor (dBm)
    snr: float                     # Network avg SNR (dB)
    airtime_utilization: float     # Total medium occupancy (%)
    retry_rate: float              # Network avg PER (0.0–1.0)
    qoe_score: float               # Network avg QoE (0–100)
    qoe_category: str
    interference_type: str = "None"
    distance: float = 0.0          # Network avg client distance (m)
    freq_mhz: float = 5180.0
    tx_power: float = 20.0         # AP transmit power (dBm)
    wall_count: int = 0            # Network avg wall count
    wall_loss: float = 0.0         # Network avg wall attenuation (dB)
    recommendations: list = None

    # ── Representative-client per-link metrics (Iteration 6) ─────────────────
    # These fields represent the client whose distance is closest to avg_dist.
    # Arithmetic averaging of dB-domain metrics (path loss, SINR, power) is
    # not physically meaningful; a representative single-link is used instead.
    path_loss_db: Optional[float] = None           # Propagation path loss (dB)
    estimated_rx_power_dbm: Optional[float] = None # Link-budget RX power: TX+Gains−PathLoss (dBm)
    sinr_db: Optional[float] = None                # Signal-to-Interference+Noise Ratio (dB)
    mcs_index: Optional[int] = None                # Selected MCS index (0–11)
    phy_rate_mbps: Optional[float] = None          # PHY data rate (Mbps)
    latency_ms: Optional[float] = None             # End-to-end latency (ms)
    throughput_mbps: Optional[float] = None        # L4 application throughput (Mbps)

    # ── Backward-compatible aliases (Iteration 1 legacy) ─────────────────────
    # sinr: kept as alias — holds same value as sinr_db for backward compat.
    # per: kept as alias — mirrors retry_rate for backward compat.
    sinr: Optional[float] = None   # Alias for sinr_db (legacy field, do not use for new code)
    per: Optional[float] = None    # Alias for retry_rate (legacy field)

    # ── Sensing Radio (Iteration 4) ───────────────────────────────────────────
    sensing_report: Optional[dict] = None

    def to_dict(self) -> dict:
        d = {
            "ap_id":               self.ap_id,
            "channel":             self.channel,
            "client_count":        self.client_count,
            "rssi":                round(self.rssi, 2),
            "noise_floor":         round(self.noise_floor, 2),
            "snr":                 round(self.snr, 2),
            "airtime_utilization": round(self.airtime_utilization, 2),
            "retry_rate":          round(self.retry_rate, 4),
            "qoe_score":           round(self.qoe_score, 1),
            "qoe_category":        self.qoe_category,
            "interference_type":   self.interference_type,
            "distance":            round(self.distance, 2),
            "freq_mhz":            round(self.freq_mhz, 1),
            "tx_power":            round(self.tx_power, 1),
            "wall_count":          self.wall_count,
            "wall_loss":           round(self.wall_loss, 2),
            "recommendations":     self.recommendations or [],
        }

        # Representative-client per-link fields
        if self.path_loss_db is not None:
            d["path_loss_db"] = round(self.path_loss_db, 2)
        if self.estimated_rx_power_dbm is not None:
            d["estimated_rx_power_dbm"] = round(self.estimated_rx_power_dbm, 2)
        if self.sinr_db is not None:
            d["sinr_db"] = round(self.sinr_db, 2)
        if self.mcs_index is not None:
            d["mcs_index"] = self.mcs_index
        if self.phy_rate_mbps is not None:
            d["phy_rate_mbps"] = round(self.phy_rate_mbps, 2)
        if self.latency_ms is not None:
            d["latency_ms"] = round(self.latency_ms, 2)
        if self.throughput_mbps is not None:
            d["throughput_mbps"] = round(self.throughput_mbps, 2)

        # Legacy alias fields
        if self.sinr is not None:
            d["sinr"] = round(self.sinr, 2)
        if self.per is not None:
            d["per"] = round(self.per, 4)

        return d
