class ClientDigitalTwin:
    client_id: str
    ap_id: str
    x: float
    y: float
    velocity_mps: float
    direction_rad: float
    device_type: str
    application_type: str
    demand_mbps: float
    antenna_gain_dbi: float
    noise_figure_db: float
